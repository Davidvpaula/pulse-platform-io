import { chromium, expect } from '@playwright/test';
import fs from 'node:fs';
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const context = await browser.newContext();
await context.route('**/*', route => ['127.0.0.1', 'localhost'].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
const page = await context.newPage();
const results = [];
const question = `FAQ navegador ${Date.now()}`;
try {
  await page.goto('http://127.0.0.1:8082/auth');
  await page.getByRole('button', { name: 'Entrar como administrador' }).click();
  await page.waitForURL('**/app/admin/dashboard');
  await expect(page.getByRole('button', { name: /Exportar/ })).toBeVisible();
  const downloadEvent = page.waitForEvent('download');
  await page.getByRole('button', { name: /Exportar/ }).click();
  const download = await downloadEvent;
  expect(download.suggestedFilename()).toMatch(/\.csv$/);
  results.push('Dashboard: exportação CSV pelo botão');
  await page.goto('http://127.0.0.1:8082/app/admin/faq');
  await page.getByRole('button', { name: 'Novo FAQ' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('input').first().fill(question);
  await dialog.locator('textarea').fill('Resposta de teste local');
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(dialog).toBeHidden();
  const card = page.locator('div.rounded-lg.border').filter({ has: page.getByText(question, { exact: true }) }).first();
  await expect(card).toBeVisible();
  await card.getByRole('button', { name: 'Editar FAQ' }).click();
  await dialog.locator('textarea').fill('Resposta alterada no navegador');
  await dialog.getByRole('button', { name: 'Salvar', exact: true }).click();
  await expect(card).toContainText('Resposta alterada no navegador');
  page.once('dialog', d => d.accept());
  await card.getByRole('button', { name: 'Excluir FAQ' }).click();
  await expect(page.getByText(question, { exact: true })).toHaveCount(0);
  results.push('FAQ: criação, edição e exclusão pela interface');
  await page.goto('http://127.0.0.1:8082/app/admin/impersonar');
  const row = page.getByRole('row').filter({ hasText: 'colaborador@pulse.local' }).first();
  await row.getByRole('button', { name: 'Visualizar', exact: true }).click();
  await dialog.locator('textarea').fill('Validação local pelo navegador');
  await dialog.getByRole('button', { name: /Iniciar|Confirmar/ }).click();
  await expect(page.getByRole('heading', { name: 'Inspeção do usuário' })).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Permissões efetivas' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Permissões efetivas' })).toBeVisible();
  await page.getByRole('button', { name: 'Encerrar inspeção' }).click();
  await expect(page.getByRole('heading', { name: 'Visualizar como' })).toBeVisible();
  results.push('Inspeção: entrada, leitura, recarga da página e encerramento');
} finally {
  fs.writeFileSync('docs/admin-funcional/navegador-local.json', JSON.stringify({ testedAt: new Date().toISOString(), passed: results }, null, 2) + '\n');
  await browser.close();
}
console.log(results.join('\n'));
